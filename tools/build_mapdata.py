# Converts assets/map.jpg into src/mapdata.js (RGB565 at 4px blocks, base64) so terrain.js can read
# surface colour / classes without decoding an image (works in the browser and in Node tests).
import base64, struct
from PIL import Image
im = Image.open('assets/map.jpg').convert('RGB')
B = 4
w, h = im.width // B, im.height // B
small = im.resize((w, h), Image.BOX)
buf = bytearray()
for y in range(h):
    for x in range(w):
        r, g, b = small.getpixel((x, y))
        buf += struct.pack('<H', ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
open('src/mapdata.js', 'w').write(
    '// generated by tools/build_mapdata.py - do not edit\n'
    f'export const MAP_W = {w}, MAP_H = {h}, MAP_BLOCK = {B}, MAP_IMG_W = {im.width}, MAP_IMG_H = {im.height};\n'
    f'export const MAP_B64 = "{base64.b64encode(bytes(buf)).decode()}";\n')
print(w, h, len(buf)//1024, 'KB raw')
